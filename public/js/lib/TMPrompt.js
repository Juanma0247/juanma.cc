export function buildAIPrompt(userDesc) {
  return [
    'You are an expert in Turing machines and formal computation theory. I need you to design a Turing machine and return it as a JSON object I can import into a simulator.',
    '',
    '## Task',
    'Design a Turing machine that does the following:',
    userDesc,
    '',
    '## Required JSON format',
    'Return ONLY a valid JSON object with exactly these fields — no extra text, no markdown code blocks:',
    '',
    '{',
    '  "title": "Short descriptive name (max 70 characters)",',
    '  "description": "One or two sentences describing what the machine does and how it works",',
    '  "author": "AI Generated",',
    '  "alphabet": "space-separated symbols — do NOT include # (it is the implicit blank). Example: \\"1 0 a\\"",',
    '  "states": ["q0", "q1", "q2"],',
    '  "initState": "q0",',
    '  "tape": "representative example tape — characters must be from the alphabet; use # for blanks",',
    '  "trans": {',
    '    "currentState,readSymbol": "writeSymbolDirectionNextState"',
    '  }',
    '}',
    '',
    '## Transition format',
    'Each key in "trans" is "state,symbol" — e.g. "q0,1" or "q1,#"',
    'Each value is a 3-part string:',
    '  1. writeSymbol — single character from the alphabet or # (blank)',
    '  2. Direction   — R (move right) or L (move left)',
    '  3. nextState   — e.g. q0, q1, q2',
    '',
    'Example: "1Rq1" means write 1, move Right, go to q1',
    'Example: "#Lq0" means write blank, move Left, go to q0',
    '',
    '## Design rules',
    '- State names must follow qN pattern: q0, q1, q2, q3 ...',
    '- The blank symbol # is always available — never include it in "alphabet"',
    '- The machine HALTS on a state-symbol pair with no defined transition (final combination)',
    '- All symbols in transitions must be from alphabet union {#}',
    '- All states in transitions must appear in the "states" array',
    '- "initState" must be a member of "states"',
    '- "tape" characters must be from the alphabet (blanks are # or empty)',
    '- Include a "tape" that shows the machine working on a typical input',
    '',
    '## Reference example',
    '{',
    '  "title": "Swap 0 and 1",',
    '  "description": "Complements every bit in a binary string. Halts at the first blank.",',
    '  "author": "AI Generated",',
    '  "alphabet": "0 1",',
    '  "states": ["q0"],',
    '  "initState": "q0",',
    '  "tape": "1011010",',
    '  "trans": {',
    '    "q0,0": "1Rq0",',
    '    "q0,1": "0Rq0"',
    '  }',
    '}',
    '',
    'Now design the Turing machine for the task above and return only the JSON.',
  ].join('\n')
}
