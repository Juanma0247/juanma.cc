export function buildAIPrompt({ title, description, alphabet, reads, does, finalState, tape, notes, filename }) {
  const specs = [
    `- Title (use this exact string for the "title" field): ${title}`,
  ]
  if (description) specs.push(`- Description (use this for the "description" field): ${description}`)
  specs.push(
    `- Input alphabet Σ: ${alphabet}`,
    `  (# is the implicit blank — it is NEVER part of Σ, but is always available on the tape)`,
    `- What the tape receives: ${reads}`,
    `- What the machine must do: ${does}`,
  )
  if (finalState) specs.push(`- Expected tape after halting: ${finalState}`)
  if (tape)       specs.push(`- Concrete example tape: ${tape}`)
  if (notes)      specs.push(`- Edge cases / additional constraints: ${notes}`)

  return [
    '# Turing Machine JSON — for import into an existing web application',
    '',
    '══════════════════════════════════════════',
    '  WHAT YOU MUST DELIVER',
    '══════════════════════════════════════════',
    'A single, valid JSON file ready to import into my Turing Machine Lab web application.',
    '',
    '!! CRITICAL — Read before doing anything else !!',
    '✗ Do NOT simulate the machine yourself.',
    '✗ Do NOT create a Turing machine widget, canvas, or interactive element.',
    '✗ Do NOT run the machine step by step inside your response.',
    '✗ Do NOT use Code Interpreter to execute anything.',
    '✗ Do NOT produce Python, JavaScript, or any other code.',
    'Your one and only deliverable is the JSON object described below.',
    '',
    '══════════════════════════════════════════',
    '  HOW THE APPLICATION WORKS',
    '══════════════════════════════════════════',
    'The JSON is imported into a web Turing Machine Lab that already exists and already runs.',
    'Understanding how the app reads the JSON is essential to producing a correct file.',
    '',
    'Field mapping inside the application:',
    '',
    '  "alphabet"   → The app builds one table column per symbol in this list.',
    '                 It also always adds # as the last column automatically.',
    '                 NEVER include # here — it causes a duplicate column error.',
    '',
    '  "states"     → The app builds one table row per state in this list.',
    '                 State names MUST follow the pattern qN (q0, q1, q2 …).',
    '                 Any other format (q_0, state1, A, halt) will break the table.',
    '',
    '  "initState"  → The app marks this state with a ▶ indicator.',
    '                 It must be an exact member of "states".',
    '',
    '  "trans"      → Each entry fills one cell of the transition table.',
    '                 Key format:   "currentState,readSymbol"  e.g. "q0,1" or "q2,#"',
    '                 Value format: "writeSymbolDirectionNextState" — compact, no spaces',
    '                   writeSymbol : exactly one char ∈ alphabet ∪ {#}',
    '                   Direction   : R (right) or L (left) — uppercase only',
    '                   nextState   : must be a member of "states"',
    '                 Examples: "1Rq1"  "#Lq0"  "aRq3"',
    '',
    '  "tape"       → Pre-fills the tape input field. Characters must be from the alphabet.',
    '                 Use # for blank cells. This is the default example shown to the user.',
    '',
    '  "title"      → Shown on the machine card in the library.',
    '  "description"→ Shown in the library detail view and on load.',
    '  "author"     → Shown in the library detail view.',
    '',
    'Halt semantics:',
    '  The machine halts when it reaches a (state, symbol) pair NOT listed in "trans".',
    '  There are no explicit accept/reject states. Halting IS the final configuration.',
    '  Intentional halts are encoded by simply omitting those pairs from "trans".',
    '  Unintentional missing transitions cause premature halts — a common design bug.',
    '',
    '══════════════════════════════════════════',
    '  MACHINE SPECIFICATIONS',
    '══════════════════════════════════════════',
    ...specs,
    '',
    '══════════════════════════════════════════',
    '  DESIGN PROCESS  (follow every step before writing JSON)',
    '══════════════════════════════════════════',
    'STEP 1 — Formal analysis',
    '  a. Define Γ = Σ ∪ {#} ∪ {auxiliary symbols if needed}.',
    '  b. Assign a one-line invariant to each state you plan to use.',
    '     Example: "q0 = scanning right, have not seen a 1 yet"',
    '  c. List all (state, symbol) pairs that must HALT and confirm they are intentional.',
    '',
    'STEP 2 — Transition table',
    '  a. For every reachable (state, symbol) pair that is NOT a halt, write the transition.',
    '  b. Explicitly handle # in every state that can reach the tape boundary.',
    '  c. Verify no reachable pair is accidentally omitted (accidental halt = bug).',
    '',
    'STEP 3 — Dry-run trace',
    `  a. Trace the machine step by step on: "${tape || '(the example tape you choose for the JSON)'}"`,
    '  b. At each step write: (state, head position, symbol read, symbol written, direction).',
    '  c. Confirm the tape content at halt matches the expected output.',
    '  d. Trace at least one edge case (empty tape, single symbol, boundary overflow).',
    '',
    'STEP 4 — Minimality & correctness',
    '  a. Can any two states be merged without changing behavior? Merge them.',
    '  b. Does every state in "states" appear in at least one transition? Remove orphan states.',
    '  c. Re-read the specification — does the machine match it exactly?',
    '',
    '══════════════════════════════════════════',
    '  REQUIRED JSON STRUCTURE',
    '══════════════════════════════════════════',
    '{',
    '  "title":       "Short name (max 70 chars)",',
    '  "description": "2–3 sentences: what it computes, how states are organized,',
    '                  and what the tape looks like after halting.",',
    '  "author":      "AI Generated",',
    '  "alphabet":    "space-separated input symbols — NEVER include #",',
    '  "states":      ["q0", "q1", "q2"],',
    '  "initState":   "q0",',
    '  "tape":        "example input — only alphabet symbols; # for blanks",',
    '  "trans": {',
    '    "state,symbol": "writeSymbolDirectionNextState"',
    '  }',
    '}',
    '',
    '══════════════════════════════════════════',
    '  PRE-OUTPUT CHECKLIST  (verify every item)',
    '══════════════════════════════════════════',
    '☐ "alphabet" has NO # character',
    '☐ All state names are qN — no other format',
    '☐ "initState" is an exact member of "states"',
    '☐ Every state in "trans" values appears in "states"',
    '☐ Every symbol in "trans" keys and values belongs to alphabet ∪ {#}',
    '☐ Every transition value is [char][R|L][qN] with no spaces',
    '☐ Dry-run confirmed: correct output on the example tape',
    '☐ No reachable (state, symbol) pair is accidentally absent from "trans"',
    '☐ "tape" characters are all from the alphabet (or #)',
    '☐ "description" matches the machine\'s actual, verified behavior',
    '',
    '══════════════════════════════════════════',
    '  COMMON MISTAKES — DO NOT MAKE THESE',
    '══════════════════════════════════════════',
    '✗ "alphabet": "0 1 #"          → # must never appear in alphabet',
    '✗ State names: "q_0", "start", "accept", "A"  → only qN format is valid',
    '✗ Transition value: "1 R q1"   → spaces break parsing; must be "1Rq1"',
    '✗ Transition value: "1,R,q1"   → commas break parsing; must be "1Rq1"',
    '✗ State in trans not in states → the app will reject the file on import',
    '✗ Missing # transition in a state that can reach the tape boundary → premature halt',
    '',
    '══════════════════════════════════════════',
    '  REFERENCE EXAMPLE  (study this carefully)',
    '══════════════════════════════════════════',
    'The example below is a real machine that runs correctly in the application.',
    'Your output must follow this exact structure.',
    '',
    '```json',
    '{',
    '  "title": "Binary Increment",',
    '  "description": "Adds 1 to a binary number. q0 scans right to find the end; q1 propagates carry leftward flipping 1→0 until it finds a 0 or the left edge; q2 is the halt state. Tape \\"1011\\" (=11) becomes \\"1100\\" (=12).",',
    '  "author": "AI Generated",',
    '  "alphabet": "0 1",',
    '  "states": ["q0", "q1", "q2"],',
    '  "initState": "q0",',
    '  "tape": "1011",',
    '  "trans": {',
    '    "q0,0": "0Rq0",',
    '    "q0,1": "1Rq0",',
    '    "q0,#": "#Lq1",',
    '    "q1,1": "0Lq1",',
    '    "q1,0": "1Lq2",',
    '    "q1,#": "1Lq2"',
    '  }',
    '}',
    '```',
    '',
    'Verified trace on "1011":',
    '  q0@0:1→keep→R | q0@1:0→keep→R | q0@2:1→keep→R | q0@3:1→keep→R',
    '  q0@4:#→#→L→q1 | q1@3:1→0→L→q1 | q1@2:1→0→L→q1 | q1@1:0→1→L→q2',
    '  HALT — tape = "1100"  ✓  (11 + 1 = 12)',
    '',
    '══════════════════════════════════════════',
    '  FINAL OUTPUT FORMAT',
    '══════════════════════════════════════════',
    'Respond in this exact order — nothing else:',
    '',
    '1. Design notes (4–6 lines):',
    '   - One line per state: "qN — [invariant / role]"',
    '   - Final line: "Trace on [tape]: [brief result]"',
    '',
    '2. The JSON in a ```json code block.',
    '',
    `3. Downloadable file named ${filename}:`,
    `   • If you are Claude  → create an Artifact (type: application/json, name: ${filename})`,
    `   • If you are ChatGPT → offer a download via Code Interpreter or Canvas as ${filename}`,
    `   • If you are Gemini  → instruct the user to copy the code block and save as ${filename}`,
    '',
    '4. One sentence: "On input \\"[tape]\\" the machine halts in state [qN] with tape \\"[result]\\"."',
  ].join('\n')
}
