const dicts = { en, es }

function lookup(obj, key) {
  return key.split('.').reduce((o, k) => (o == null ? o : o[k]), obj)
}

export function currentLang() {
  if (typeof window !== 'undefined' && window.__lang) return window.__lang
  const nav = typeof navigator !== 'undefined' ? navigator.language || 'en' : 'en'
  return nav.toLowerCase().startsWith('es') ? 'es' : 'en'
}

export function t(key, vars) {
  let val = null
  if (typeof window !== 'undefined' && window.i18nGet) val = window.i18nGet('pd.notes.' + key, null)
  if (val == null || val === 'pd.notes.' + key) val = lookup(dicts[currentLang()] ?? en, key) ?? lookup(en, key) ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) val = val.replaceAll(`{${k}}`, String(v))
  return val
}
